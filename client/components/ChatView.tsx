import { Terminal, User, Zap, Play, Check, Sparkles } from "lucide-react";
import { useState, useRef, KeyboardEvent, ChangeEvent } from "react";
import { useSelector } from "react-redux";
import { RootState } from "@/store";

export default function ChatView() {
  const selectedDbIds = useSelector((state: RootState) => state.app.selectedDbIds);
  const activeChatId = useSelector((state: RootState) => state.app.activeChatId);
  
  const [prompt, setPrompt] = useState("");
  const [messages, setMessages] = useState<any[]>([]); 
  const textareaRef = useRef<HTMLTextAreaElement>(null);

  const handleGenerate = async () => {
    if (!prompt.trim()) return;
    
    if (selectedDbIds.length === 0) {
      alert("Please select at least one database from the header dropdown.");
      return;
    }
    
    // Add user message to UI immediately
    setMessages(prev => [...prev, { id: Date.now(), role: "user", content: prompt.trim() }]);
    const currentPrompt = prompt.trim();
    setPrompt(""); 
    if (textareaRef.current) textareaRef.current.style.height = "auto";
    
    try {
      // Send the prompt AND the target database ID(s) from Redux to your backend
      const response = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          prompt: currentPrompt,
          databaseId: selectedDbIds[0], // Pass the active DB context to Flask
          chatId: activeChatId 
        })
      });

      const data = await response.json();
      
      // Append AI response (SQL + Data generated by Flask) to UI
      setMessages(prev => [...prev, { 
        id: Date.now(), 
        role: "ai", 
        content: "Here is your generated query and data.", 
        sql: data.sql_string,
        rows: data.rows // Expecting Flask to return execution data
      }]);
      
    } catch (error) {
      console.error("Failed to generate SQL", error);
    }
  };

  // Handle Shift+Enter for new line, Enter for submit
  const handleKeyDown = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault(); // Prevent adding a new line
      handleGenerate();
    }
  };

  const handleInput = (e: ChangeEvent<HTMLTextAreaElement>) => {
    setPrompt(e.target.value);
    if (textareaRef.current) {
      // Reset height to recalculate on backspace, then set to scrollHeight
      textareaRef.current.style.height = "auto";
      // Cap the max height to 200px so it eventually scrolls instead of taking over the whole screen
      textareaRef.current.style.height = `${Math.min(textareaRef.current.scrollHeight, 200)}px`;
    }
  };
  
  // =========================================
  // VIEW 1: EMPTY STATE (VERTICALLY CENTERED)
  // =========================================
  if (messages.length === 0) {
    return (
      <div className="flex-1 flex flex-col items-center justify-center h-full animate-in fade-in duration-500 p-8 relative z-0">
        <div className="w-full max-w-3xl flex flex-col items-center">
          <div className="bg-indigo-500/10 border border-indigo-500/20 text-indigo-400 p-3 rounded-2xl mb-6 shadow-[0_0_30px_rgba(99,102,241,0.1)]">
            <Sparkles size={32} />
          </div>
          <h2 className="text-4xl font-extrabold text-white tracking-tight mb-8 text-center">
            What data do you need?
          </h2>
          
          {/* Dark Mode Input Wrapper */}
          <div className="w-full relative shadow-2xl rounded-2xl group bg-slate-900/80 backdrop-blur-sm border border-slate-800 focus-within:ring-2 focus-within:ring-indigo-500/50 focus-within:border-indigo-500 transition-all">
            <textarea 
              ref={textareaRef}
              rows={1}
              value={prompt}
              onChange={handleInput}
              onKeyDown={handleKeyDown}
              placeholder="Ask a question... (Shift + Enter for new line)" 
              className="w-full bg-transparent px-6 py-5 pr-40 text-slate-200 placeholder-slate-500 font-medium focus:outline-none text-lg resize-none min-h-[68px] max-h-[200px] overflow-y-auto" 
            />
            {/* Fixed Button */}
            <button 
              onClick={handleGenerate}
              className="absolute right-3 bottom-3 h-[44px] bg-indigo-600 text-white px-6 rounded-xl hover:bg-indigo-500 flex items-center gap-2 font-bold shadow-lg shadow-indigo-900/20 transition-all transform hover:scale-105 active:scale-95"
            >
              <Terminal size={18} /> Generate
            </button>
          </div>
          <p className="text-slate-500 text-sm mt-4 font-medium">Press Enter to run, Shift + Enter for new line.</p>
        </div>
      </div>
    );
  }

  // =========================================
  // VIEW 2: ACTIVE CHAT (INPUT AT BOTTOM)
  // =========================================
  return (
    <div className="flex flex-col h-full relative animate-in fade-in duration-300 z-0">
      
      {/* CHAT HISTORY */}
      <div className="flex-1 overflow-y-auto p-8 space-y-8 pb-40">
        {messages.map((msg) => (
          <div key={msg.id} className={`flex gap-4 max-w-4xl mx-auto ${msg.role === "user" ? "flex-row-reverse" : ""}`}>
            
            {/* Dark Mode Avatars */}
            <div className={`w-10 h-10 rounded-full flex items-center justify-center shrink-0 shadow-sm ${
              msg.role === "user" ? "bg-indigo-500/20 text-indigo-400 border border-indigo-500/30" : "bg-gradient-to-br from-indigo-500 to-violet-500 text-white"
            }`}>
              {msg.role === "user" ? <User size={20} /> : <Zap size={20} />}
            </div>

            <div className={`flex flex-col gap-2 max-w-[80%] ${msg.role === "user" ? "items-end" : "items-start"}`}>
              {/* Dark Mode Bubbles */}
              <div className={`px-5 py-3.5 rounded-2xl text-sm font-medium shadow-sm whitespace-pre-wrap ${
                msg.role === "user" ? "bg-indigo-600 text-white rounded-tr-sm" : "bg-slate-900 border border-slate-800 text-slate-300 rounded-tl-sm shadow-md"
              }`}>
                {msg.content}
              </div>

              {/* SQL Code Block */}
              {msg.sql && (
                <div className="w-full mt-2 bg-slate-950 rounded-xl overflow-hidden border border-slate-800 shadow-md">
                  <div className="flex items-center justify-between px-4 py-2 bg-slate-900/50 border-b border-slate-800">
                    <span className="text-xs font-mono text-slate-400">Generated SQL</span>
                    <div className="flex gap-2">
                      <button onClick={handleCopy} className="text-slate-400 hover:text-white transition-colors flex items-center gap-1.5 text-xs font-medium px-2 py-1">
                        {copied ? <Check size={14} className="text-green-400" /> : "Copy"}
                      </button>
                      <button className="bg-indigo-600 hover:bg-indigo-500 text-white transition-colors flex items-center gap-1.5 text-xs font-bold px-3 py-1 rounded-md">
                        <Play size={12} fill="currentColor" /> Run
                      </button>
                    </div>
                  </div>
                  <div className="p-4 overflow-x-auto">
                    <pre className="text-sm font-mono text-indigo-300 leading-relaxed">
                      <code>{msg.sql}</code>
                    </pre>
                  </div>
                </div>
              )}
            </div>
          </div>
        ))}
      </div>

      {/* Dark Mode Input Bar (Fixed at bottom) */}
      <div className="absolute bottom-0 left-0 right-0 p-8 bg-gradient-to-t from-slate-950 via-slate-950 to-transparent pt-12">
        
        {/* Input Wrapper */}
        <div className="max-w-4xl mx-auto w-full relative bg-slate-900/90 backdrop-blur-md border border-slate-700 rounded-2xl focus-within:ring-2 focus-within:ring-indigo-500/50 focus-within:border-indigo-500 shadow-2xl transition-all">
          <textarea 
            ref={textareaRef}
            rows={1}
            value={prompt}
            onChange={handleInput}
            onKeyDown={handleKeyDown}
            placeholder="Ask a follow-up question..." 
            className="w-full bg-transparent px-5 py-4 pr-40 text-slate-200 placeholder-slate-500 font-medium focus:outline-none text-base resize-none min-h-[58px] max-h-[200px] overflow-y-auto rounded-2xl" 
          />
          {/* Fixed Button */}
          <button 
            onClick={handleGenerate}
            className="absolute right-2 bottom-2 h-[42px] bg-indigo-600 text-white px-6 rounded-xl hover:bg-indigo-500 flex items-center gap-2 font-bold shadow-lg shadow-indigo-900/20 transition-all"
          >
            <Terminal size={18} /> Generate
          </button>
        </div>

      </div>
    </div>
  );
}


